#!/usr/bin/env python3
"""Generate src/cp932_table.h: the Shift-JIS (CP932) double-byte -> UCS-2 map.

Old TJA charts are Shift-JIS. The player converts them itself (so a chart can
simply be copied to the handheld), using this table. Regenerate with:
    python3 tools/gen_cp932.py > src/cp932_table.h

Layout: lead bytes 0x81-0x9F then 0xE0-0xFC (60 leads), trail bytes
0x40-0xFC (189 trails). 0 = unmapped.
"""
LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = list(range(0x40, 0xFD))

print("/* Generated by tools/gen_cp932.py from Python's cp932 codec. Do not edit. */")
print("#ifndef CP932_TABLE_H")
print("#define CP932_TABLE_H")
print("#include <stdint.h>")
print(f"#define CP932_LEADS {len(LEADS)}")
print(f"#define CP932_TRAILS {len(TRAILS)}")
print("static const uint16_t cp932_table[CP932_LEADS * CP932_TRAILS] = {")
for lead in LEADS:
    row = []
    for trail in TRAILS:
        try:
            ch = bytes([lead, trail]).decode("cp932")
            cp = ord(ch) if len(ch) == 1 and ord(ch) < 0x10000 else 0
        except UnicodeDecodeError:
            cp = 0
        row.append(cp)
    print("  " + ",".join(f"0x{v:04X}" if v else "0" for v in row) + ",")
print("};")
print("#endif")
